from __future__ import annotations

from typing import Any, Generator

import numpy as np
from scipy.spatial.transform import Rotation as R


class OuterControlLoop:
    """Outer control loop for executing learned policies with a robotic system.

    This class manages the high-level execution of a context-adaptive policy by
    interfacing with a robot controller. It handles data input/output with the robot,
    combines LfD policies with stabilizing and goal attractor policies, and monitors
    execution success.

    The loop reads the current TCP frame, and task parameters,
    then computes velocity commands through the CAPOF framework and sends them
    to the robot until convergence or a stop condition is reached.

    Args:
        X: array-like of shape (n_samples, n_features). Demonstration data used to
            normalize success thresholds.
        capof: The :class:`~capof.capof.ContextAdaptivePolicyFramework` instance.
        offset: array-like. Absolute offset added to the success threshold for each
            dimension.
        loop_limit: int (default 1000). Maximum number of control iterations before
            forced stop.
        threshold: float (default 0.01). Relative distance threshold for considering
            the goal reached.
        policy_combination: str (default "MoE"). Policy combination method. Possible
            values: 'LfD', 'Stabilizing', 'Goal', 'LfD + Stabilizing', 'LfD + Goal',
            'MoE'.
    """

    def __init__(
        self,
        X: np.ndarray,
        capof: Any,
        offset: np.ndarray,
        loop_limit: int = 1000,
        threshold: float = 0.01,
        policy_combination: str = "MoE",
    ) -> None:
        # Save variables
        self.X = X
        self.capof = capof
        self.offset = offset

        self.loop_limit = loop_limit
        self.threshold = threshold
        self.policy_combination = policy_combination

        # Attributes set during the execution loop (declared here for typing;
        # see the method that sets each one):
        self.tcp_frame: np.ndarray  # current TCP frame (set by the subclass)
        self.lfd_input: np.ndarray  # LfD input vector (_create_LfD_input)
        self.vel_twist: np.ndarray  # velocity command (_velocity_calculation)
        self.mu_add: np.ndarray  # additional policy output (_velocity_calculation)
        self.task_parameters: np.ndarray  # task parameters (_read_current_task_parameters)
        self.hand_pose: np.ndarray  # hand/gripper pose (_read_current_hand_pose)

    def _parameter_initialization(self) -> None:
        """Initialize process parameters for a new execution run.

        Sets up the stop flag, and success counter. Also reads the initial task
        parameters and hand pose if applicable.
        """
        # Initialize process parameters
        self.stop_activated = False
        self.success = False
        self.success_counter = 0

        if self.capof.c_dim != 0:
            # Read current task-parameters if provided (blocking)
            self._read_current_task_parameters(True)
        else:
            self.task_parameters = np.array([])

        # Read current hand pose
        if self.capof.mu_add_dim != 0:
            self._read_current_hand_pose(True)

    def _state_based_execution_loop(self) -> None:
        """Run the state-based execution loop until completion or stop condition.

        Iterates through control frames generated by :meth:`_gen`, updating the
        system state at each step. Ensures safe shutdown when the loop terminates.
        """
        # Run control loop
        for frame in self._gen():
            self._update(frame)

        # Safe robot shutdown
        self._safe_shutdown()

    def _gen(self) -> Generator[int, None, None]:
        """Generate control frame indices until a stop condition is reached.

        Yields:
            int: Frame index starting from 1, incremented each iteration.
        """
        i = 0
        while not self.success and not self.stop_activated and i < self.loop_limit:
            i += 1
            yield i

    def _update(self, frame: int) -> None:
        """Execute one control loop iteration.

        Reads sensor data, computes velocity commands via the CAPOF framework,
        performs safety checks, and sends commands to the robot.

        Args:
            frame: Current frame index (from :meth:`_gen`).
        """
        # Read current tcp frame (blocking -> loop time)
        self._read_current_tcp_frame()

        # Read current task-parameters if provided (non-blocking)
        if self.capof.c_dim != 0:
            self._read_current_task_parameters(False)

        # Read current hand pose
        if self.capof.mu_add_dim != 0:
            self._read_current_hand_pose(False)

        # Pre-process LfD input data
        self._preprocess_data()

        # Combine task-parameters and pose for LfD input
        self._create_LfD_input()

        # Calculate new velocity and hand position
        self._velocity_calculation()

        # Post-process LfD output data
        self._postprocess_data()

        # Check for (robot) limits
        self._check_for_limits()

        # Safety check for type, shape, dtype, NaN and inf
        self._value_safety_check()

        # Publish velocity information
        self._publish_vel_info()

        try:
            # Send command to robot
            self._send_command_to_robot()
        except Exception:
            # Shut down robot safely
            self._safe_shutdown()
            raise

        # Check for success
        self._check_for_success()

        # Check for stop signal
        self._check_for_external_stop()
        return

    def _create_LfD_input(self) -> None:
        """Combine task parameters and pose into the LfD input vector."""
        # Convert current frame to (x, y, z, qx, qy, qz)
        rotvec_frame = np.concatenate((self.tcp_frame[:3, 3], R.from_matrix(self.tcp_frame[:3, :3]).as_rotvec()), axis=-1)

        # Combine task-parameters and pose for LfD input
        self.lfd_input = np.concatenate(
            (
                self.task_parameters[: self.capof.c_dim],
                rotvec_frame[: self.capof.x_dim],
                rotvec_frame[3 : 3 + self.capof.phi_dim],
            )
        )

    def _velocity_calculation(self) -> None:
        """Compute the velocity command with the CAPOF policy combination.

        Evaluates the combined policy (see
        :meth:`capof.capof.ContextAdaptivePolicyFramework.compute_moe`) on the
        current LfD input and stores the resulting velocity twist and the
        additional (e.g. gripper) command in :attr:`vel_twist` / :attr:`mu_add`.
        """
        vel_twist, mu_add, (mu_sp, mu_gap, epi, k_max) = self.capof.compute_moe(
            self.lfd_input.reshape(1, -1), self.policy_combination
        )

        self.vel_twist, self.mu_add = vel_twist[0], mu_add[0]

    def _value_safety_check(self):
        """Verify that the computed velocity is safe to send to the robot.

        Checks that vel_twist is a float64 ndarray with the correct shape and
        contains no NaN or infinite values. Triggers safe shutdown on failure.

        Raises:
            TypeError: If vel_twist fails any safety check.
        """
        # Safety check for type, shape, dtype, NaN and inf
        if (
            not isinstance(self.vel_twist, np.ndarray)
            or self.vel_twist.shape != (self.capof.x_dot_dim + self.capof.phi_dot_dim,)
            or self.vel_twist.dtype != np.float64
            or np.isnan(self.vel_twist).any()
            or np.isinf(self.vel_twist).any()
        ):
            self._safe_shutdown()
            raise TypeError("Wrong value type encountered in velocity twist")

    def _check_for_success(self) -> None:
        """Check whether the current state is within threshold of a goal pose.

        Compares the current pose (excluding task parameters) against all goal
        poses. Sets the success flag after 10 consecutive successful frames.
        """
        if np.any(
            np.all(
                abs(self.lfd_input[self.capof.c_dim :] - self.capof.goal_poses[:, self.capof.c_dim :])
                < self.threshold
                * (np.max(self.X[:, self.capof.c_dim :], axis=0) - np.min(self.X[:, self.capof.c_dim :], axis=0))
                + self.offset,
                axis=1,
            )
        ):
            self.success_counter += 1
            if self.success_counter == 10:
                self.success = True
        else:
            self.success_counter = 0
        return

    def _read_current_tcp_frame(self) -> None:
        """Read the current tool-center-point (TCP) frame from the robot.

        Must be implemented by subclasses to interface with specific robot hardware.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _read_current_task_parameters(self, blocking: bool) -> None:
        """Read the current task parameters (e.g., object pose) from the robot.

        Args:
            blocking: If True, block until parameters are available; otherwise
                return immediately.

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _read_current_hand_pose(self, blocking: bool) -> None:
        """Read the current hand pose from the robot.

        Args:
            blocking: If True, block until pose is available; otherwise return
                immediately.

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _read_current_image_frame(self, blocking: bool) -> None:
        """Read the current image frame from the robot's camera.

        Args:
            blocking: If True, block until frame is available; otherwise return
                immediately.

        Must be implemented by subclasses when image_encoder is True.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _preprocess_data(self) -> None:
        """Preprocess LfD input data before policy query.

        Override in subclasses to apply transforms.

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _postprocess_data(self) -> None:
        """Postprocess LfD output data after policy query.

        Override in subclasses to apply transforms to the computed velocity.

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _check_for_limits(self) -> None:
        """Check whether robot joint or workspace limits have been reached.

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _publish_vel_info(self) -> None:
        """Publish velocity information (e.g., for logging or visualisation).

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _send_command_to_robot(self) -> None:
        """Send the computed velocity command to the robot.

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _safe_shutdown(self) -> None:
        """Execute a safe shutdown procedure (e.g., stop motion).

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")

    def _check_for_external_stop(self) -> None:
        """Check for an external stop signal (e.g., from a user or a safety controller).

        Must be implemented by subclasses.
        """
        raise NotImplementedError("Subclasses must implement this method.")
